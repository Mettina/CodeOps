# Basic Python List/Array Operations

# Create a list containing 10 student names
students = ["Almaz", "Bekele", "Chala", "Dawit", "Etenesh", "Fatuma", "Girma", "Hana", "Ibrahim", "Juweriya"]

# 1. Accessing an element by index (Index 0 is the first element)
print(students[0])

# 2. Adding an element at the very end of the list using append()
students.append("Kamil")
print(students)

# 3. Inserting an element at position 0 (the beginning) using insert()
students.insert(0, "Lensa")
print(students)
